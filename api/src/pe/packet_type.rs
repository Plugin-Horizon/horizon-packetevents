/// The protocol states a packet can be in.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ConnectionState {
    Handshaking,
    Status,
    Login,
    Configuration,
    Play,
}

/// Any packet type of 26.3, with its side.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum PacketType {
    PlayServer(PlayServer),
    PlayClient(PlayClient),
    ConfigurationServer(ConfigurationServer),
    ConfigurationClient(ConfigurationClient),
    LoginServer(LoginServer),
    LoginClient(LoginClient),
}

impl PacketType {
    /// The state the packet belongs to.
    pub fn state(self) -> ConnectionState {
        match self {
            PacketType::PlayServer(_) | PacketType::PlayClient(_) => ConnectionState::Play,
            PacketType::ConfigurationServer(_) | PacketType::ConfigurationClient(_) => ConnectionState::Configuration,
            PacketType::LoginServer(_) | PacketType::LoginClient(_) => ConnectionState::Login,
        }
    }

    /// True for packets the server sends (clientbound).
    pub fn is_server_side(self) -> bool {
        matches!(
            self,
            PacketType::PlayServer(_) | PacketType::ConfigurationServer(_) | PacketType::LoginServer(_)
        )
    }

    /// The packet's id within its state and side.
    pub fn id(self) -> i32 {
        match self {
            PacketType::PlayServer(p) => p.id(),
            PacketType::PlayClient(p) => p.id(),
            PacketType::ConfigurationServer(p) => p.id(),
            PacketType::ConfigurationClient(p) => p.id(),
            PacketType::LoginServer(p) => p.id(),
            PacketType::LoginClient(p) => p.id(),
        }
    }

    /// The packet's name in lower case.
    pub fn name(self) -> &'static str {
        match self {
            PacketType::PlayServer(p) => p.name(),
            PacketType::PlayClient(p) => p.name(),
            PacketType::ConfigurationServer(p) => p.name(),
            PacketType::ConfigurationClient(p) => p.name(),
            PacketType::LoginServer(p) => p.name(),
            PacketType::LoginClient(p) => p.name(),
        }
    }

    /// The packet with this id in a state and side, if any.
    pub fn lookup(state: ConnectionState, server_side: bool, id: i32) -> Option<PacketType> {
        match (state, server_side) {
            (ConnectionState::Play, true) => PlayServer::from_id(id).map(PacketType::PlayServer),
            (ConnectionState::Play, false) => PlayClient::from_id(id).map(PacketType::PlayClient),
            (ConnectionState::Configuration, true) => {
                ConfigurationServer::from_id(id).map(PacketType::ConfigurationServer)
            }
            (ConnectionState::Configuration, false) => {
                ConfigurationClient::from_id(id).map(PacketType::ConfigurationClient)
            }
            (ConnectionState::Login, true) => LoginServer::from_id(id).map(PacketType::LoginServer),
            (ConnectionState::Login, false) => LoginClient::from_id(id).map(PacketType::LoginClient),
            _ => None,
        }
    }
}
